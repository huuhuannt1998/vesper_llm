    # Helper methods
    def _categorize_task(self, task_name: str) -> str:
        """Categorize task by type"""
        task_lower = task_name.lower()
        if 'cook' in task_lower or 'kitchen' in task_lower:
            return 'KITCHEN'
        elif 'sleep' in task_lower or 'bed' in task_lower:
            return 'BEDROOM'
        elif 'relax' in task_lower or 'living' in task_lower:
            return 'LIVING_ROOM'
        elif 'bathroom' in task_lower or 'wash' in task_lower:
            return 'BATHROOM'
        elif 'work' in task_lower or 'office' in task_lower:
            return 'OFFICE'
        else:
            return 'OTHER'
    
    def _extract_expected_room(self, task_name: str) -> str:
        """Extract expected room from task name"""
        return self._categorize_task(task_name)
    
    def _calculate_path_efficiency(self, movement_path: List[Dict]) -> float:
        """Calculate path efficiency (straight line distance / actual path distance)"""
        if len(movement_path) < 2:
            return 1.0
        
        start_pos = movement_path[0]['from_position']
        end_pos = movement_path[-1]['to_position']
        
        # Straight line distance
        straight_distance = math.sqrt((end_pos[0] - start_pos[0])**2 + (end_pos[1] - start_pos[1])**2)
        
        # Actual path distance
        actual_distance = 0.0
        for i in range(len(movement_path)):
            step = movement_path[i]
            from_pos = step['from_position']
            to_pos = step['to_position']
            actual_distance += math.sqrt((to_pos[0] - from_pos[0])**2 + (to_pos[1] - from_pos[1])**2)
        
        if actual_distance == 0:
            return 1.0
        
        return min(1.0, straight_distance / actual_distance)
    
    def _calculate_total_distance(self) -> float:
        """Calculate total distance traveled across all tasks"""
        total_distance = 0.0
        task_details = self.log_data.get('task_details', [])
        
        for task in task_details:
            movement_path = task.get('movement_path', [])
            for step in movement_path:
                from_pos = step['from_position']
                to_pos = step['to_position']
                step_distance = math.sqrt((to_pos[0] - from_pos[0])**2 + (to_pos[1] - from_pos[1])**2)
                total_distance += step_distance
        
        return total_distance
    
    def _analyze_movement_patterns(self) -> Dict[str, int]:
        """Analyze movement direction patterns"""
        patterns = {"UP": 0, "DOWN": 0, "LEFT": 0, "RIGHT": 0, "STAY": 0}
        task_details = self.log_data.get('task_details', [])
        
        for task in task_details:
            movement_path = task.get('movement_path', [])
            for step in movement_path:
                action = step.get('action', 'UNKNOWN')
                if action in patterns:
                    patterns[action] += 1
        
        return patterns
    
    def _count_direction_changes(self, movement_path: List[Dict]) -> int:
        """Count direction changes in movement path"""
        if len(movement_path) < 2:
            return 0
        
        changes = 0
        last_direction = movement_path[0].get('action', '')
        
        for step in movement_path[1:]:
            current_direction = step.get('action', '')
            if current_direction != last_direction and current_direction != 'STAY':
                changes += 1
            last_direction = current_direction
        
        return changes
    
