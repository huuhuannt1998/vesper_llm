        log_dir = os.path.join(r"C:\Users\hbui11\Desktop\vesper_llm\blender", "evaluation_logs")
        if not os.path.exists(log_dir):
            print(f"❌ LOG ANALYZER: Log directory not found - {log_dir}")
            return None
        
